#!/usr/bin/env node
// src/install/pack.mjs — build the single self-contained tool.mjs (SPEC §2:
// "the recorder logic ships as a single self-contained tool.mjs").
//
//   node src/install/pack.mjs            # writes src/install/tool.mjs
//
// The pack inlines:
//   - adapters/vibe/tool-side.mjs  (H1 install side; node builtins only,
//     line-leading `export ` keywords — stripped here)
//   - instructions/decisions.md    (R4 text, embedded as
//     globalThis.__TONK_INSTRUCTIONS__ so the packed file needs no other file)
//
// Integration point: the full shipped tool.mjs also packs R3's hook runtime
// (src/hooks/), which must register itself as globalThis.__TONK_HOOK_RUNTIME__
// = { run(event, {env}) }. Until R3 lands, `hook <event>` fails open (exit 0).
// B0's single-file build should reuse this packer and add the hooks module.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = path.resolve(HERE, '..', '..');
export const TOOL_SIDE = path.join(REPO_ROOT, 'adapters', 'vibe', 'tool-side.mjs');
export const INSTRUCTIONS = path.join(REPO_ROOT, 'instructions', 'decisions.md');
export const OUT = path.join(HERE, 'tool.mjs');

const HEADER = `// tool.mjs — Tonk recorder logic, single-file build (SPEC §2).
// GENERATED by src/install/pack.mjs from adapters/vibe/tool-side.mjs +
// instructions/decisions.md — do not edit by hand; rerun the packer.
//
// Commands: install|uninstall|status --harness vibe · instructions ·
// hook <event> · --help · --version.  See adapters/vibe/README.md.
`;

export function packToolMjs({ toolSide = TOOL_SIDE, instructions = INSTRUCTIONS } = {}) {
  const side = fs.readFileSync(toolSide, 'utf8');
  const text = fs.readFileSync(instructions, 'utf8');
  const lines = side.split('\n');
  if (lines[0] && lines[0].startsWith('#!')) lines.shift(); // shebang: emitted once, above
  const imports = [];
  const rest = [];
  for (const line of lines) {
    if (/^import\s/.test(line)) {
      if (!/^import\s.*from\s+'node:[^']+';?\s*$/.test(line)) {
        throw new Error(`pack.mjs: non-node import in tool-side.mjs: ${line}`);
      }
      imports.push(line);
    } else {
      rest.push(line.startsWith('export ') ? line.slice('export '.length) : line);
    }
  }
  if (rest.some((l) => /^\s*import\s/.test(l))) {
    throw new Error('pack.mjs: unexpected import after the import block');
  }
  return (
    '#!/usr/bin/env node\n' +
    HEADER +
    imports.join('\n') +
    '\n\n' +
    `globalThis.__TONK_INSTRUCTIONS__ = ${JSON.stringify(text)};\n\n` +
    rest.join('\n')
  );
}

export function main() {
  const out = packToolMjs();
  fs.writeFileSync(OUT, out, { mode: 0o755 });
  process.stdout.write(`packed ${OUT} (${Buffer.byteLength(out)} bytes)\n`);
}

const isMain = (() => {
  try {
    const argv1 = process.argv[1] ? fs.realpathSync(process.argv[1]) : null;
    return !!argv1 && argv1 === fs.realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
})();

if (isMain) main();
